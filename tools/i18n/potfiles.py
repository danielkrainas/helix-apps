#!/usr/bin/env python3
"""List the files with translatable text, one per line, as po/POTFILES
holds them: Rust sources that call the i18n functions with a literal,
then the desktop files and metainfo.

    python3 tools/i18n/potfiles.py > po/POTFILES

The rule for Rust sources is the same as the unit test that checks
po/POTFILES (crates/helix-app-common/tests/potfiles.rs).

Shared with helix-desktop's tools/i18n/potfiles.py (which lists its
crates and one desktop file): keep the rule in step (see "Tooling shared
with helix-desktop" in TRANSLATING.md).
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CALL = re.compile(r'(?<![A-Za-z0-9_])(tr|trc|trn|n_)\(\s*"|(?<![A-Za-z0-9_])(trn?f|nc_)!\(')
# Not shown to people: tests, examples and test-support crates.
SKIP_DIRS = ("tests", "target", "examples", "helix-test-audio")


def rust_files():
    out = []
    for top in ("apps", "crates"):
        for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, top)):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for f in sorted(filenames):
                if f.endswith(".rs"):
                    p = os.path.join(dirpath, f)
                    rel = os.path.relpath(p, ROOT)
                    if rel == "crates/helix-app-common/src/i18n.rs":
                        continue
                    if CALL.search(open(p, encoding="utf-8").read()):
                        out.append(rel)
    return sorted(out)


def data_files():
    out = []
    apps = os.path.join(ROOT, "apps")
    for app in sorted(os.listdir(apps)):
        data = os.path.join(apps, app, "data")
        if not os.path.isdir(data):
            continue
        for f in sorted(os.listdir(data)):
            if f.endswith(".desktop") or f.endswith(".metainfo.xml"):
                out.append(f"apps/{app}/data/{f}")
    return out


def main():
    sys.stdout.write("# Generated by tools/i18n/potfiles.py; do not edit.\n")
    for f in rust_files() + data_files():
        sys.stdout.write(f + "\n")


if __name__ == "__main__":
    main()
